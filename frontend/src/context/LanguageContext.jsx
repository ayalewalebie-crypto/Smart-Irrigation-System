const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('sis_lang') || 'en');

  const switchLang = (code) => {
    setLang(code);
    localStorage.setItem('sis_lang', code);
  };

  const t = (key) => (lang === 'am' ? am[key] : en[key]) ?? en[key] ?? key;

  return (
    <LanguageContext.Provider value={{ lang, switchLang, t, translations: lang === 'am' ? am : en }}>
      {children}
    </LanguageContext.Provider>
  );
}

export const useLang = () => useContext(LanguageContext);
export default LanguageContext;
